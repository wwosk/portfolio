package org.example.mypaintings.auth.jwt;

import com.auth0.jwt.JWT;
import com.auth0.jwt.algorithms.Algorithm;
import com.auth0.jwt.exceptions.JWTVerificationException;
import com.auth0.jwt.exceptions.TokenExpiredException;
import com.auth0.jwt.interfaces.DecodedJWT;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.Date;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class JwtServiceTest {

    private static final String SECRET = "super-secret-key-with-at-least-32-chars!!";
    private static final long EXPIRATION_MS = 3_600_000L;
    private static final Long USER_ID = 42L;
    private static final String ROLE = "ARTIST";

    private JwtService jwtService;

    @BeforeEach
    void setUp() {
        // given
        jwtService = new JwtService();
        ReflectionTestUtils.setField(jwtService, "secretKey", SECRET);
        ReflectionTestUtils.setField(jwtService, "expirationMs", EXPIRATION_MS);
    }

    @Test
    @DisplayName("Should return a non-blank token consisting of three parts")
    void generateToken_shouldReturnNonBlankToken() {
        // when
        String token = jwtService.generateToken(USER_ID, ROLE);

        // then
        assertThat(token).isNotBlank();
        assertThat(token.split("\\.")).hasSize(3);
    }

    @Test
    @DisplayName("Should embed expected claims and headers into generated token")
    void generateToken_shouldContainExpectedClaims() {
        // when
        String token = jwtService.generateToken(USER_ID, ROLE);
        DecodedJWT decoded = JWT.decode(token);

        // then
        assertThat(decoded.getClaim("userId").asLong()).isEqualTo(USER_ID);
        assertThat(decoded.getClaim("role").asString()).isEqualTo("ROLE_" + ROLE);
        assertThat(decoded.getIssuer()).isEqualTo("MyPaintings");
        assertThat(decoded.getAudience()).containsExactly("mypaintings-api");
        assertThat(decoded.getIssuedAt()).isNotNull();
        assertThat(decoded.getExpiresAt()).isNotNull();
    }

    @Test
    @DisplayName("Should set expiration date according to configured expiration milliseconds")
    void generateToken_shouldSetExpirationAccordingToConfig() {
        // when
        String token = jwtService.generateToken(USER_ID, ROLE);
        DecodedJWT decoded = JWT.decode(token);
        long diff = decoded.getExpiresAt().getTime() - decoded.getIssuedAt().getTime();

        // then
        assertThat(diff).isBetween(EXPIRATION_MS - 1000, EXPIRATION_MS + 1000);
    }

    @Test
    @DisplayName("Should embed different user IDs for different users")
    void generateToken_shouldEmbedDifferentUserId_forDifferentUsers() {
        // when
        String t1 = jwtService.generateToken(1L, ROLE);
        String t2 = jwtService.generateToken(2L, ROLE);

        // then
        assertThat(JWT.decode(t1).getClaim("userId").asLong()).isEqualTo(1L);
        assertThat(JWT.decode(t2).getClaim("userId").asLong()).isEqualTo(2L);
        assertThat(t1).isNotEqualTo(t2);
    }

    @Test
    @DisplayName("Should accept valid token generated by the service")
    void verifyToken_shouldAcceptValidToken() {
        // given
        String token = jwtService.generateToken(USER_ID, ROLE);

        // when
        DecodedJWT decoded = jwtService.verifyToken(token);

        // then
        assertThat(decoded.getClaim("userId").asLong()).isEqualTo(USER_ID);
        assertThat(decoded.getClaim("role").asString()).isEqualTo("ROLE_" + ROLE);
    }

    @Test
    @DisplayName("Should reject token signed with a different secret")
    void verifyToken_shouldRejectTokenWithWrongSignature() {
        // given
        String tokenSignedWithOtherKey = JWT.create()
                .withClaim("userId", USER_ID)
                .withClaim("role", "ROLE_" + ROLE)
                .withIssuer("MyPaintings")
                .withAudience("mypaintings-api")
                .withIssuedAt(new Date())
                .withExpiresAt(new Date(System.currentTimeMillis() + EXPIRATION_MS))
                .sign(Algorithm.HMAC256("different-secret-key-that-is-long-enough-32"));

        // when & then
        assertThatThrownBy(() -> jwtService.verifyToken(tokenSignedWithOtherKey))
                .isInstanceOf(JWTVerificationException.class);
    }

    @Test
    @DisplayName("Should reject token with unexpected issuer")
    void verifyToken_shouldRejectTokenWithWrongIssuer() {
        // given
        String token = JWT.create()
                .withClaim("userId", USER_ID)
                .withClaim("role", "ROLE_" + ROLE)
                .withIssuer("SomeOtherIssuer")
                .withAudience("mypaintings-api")
                .withIssuedAt(new Date())
                .withExpiresAt(new Date(System.currentTimeMillis() + EXPIRATION_MS))
                .sign(Algorithm.HMAC256(SECRET));

        // when & then
        assertThatThrownBy(() -> jwtService.verifyToken(token))
                .isInstanceOf(JWTVerificationException.class)
                .hasMessageContaining("issuer");
    }

    @Test
    @DisplayName("Should reject token with unexpected audience")
    void verifyToken_shouldRejectTokenWithWrongAudience() {
        // given
        String token = JWT.create()
                .withClaim("userId", USER_ID)
                .withClaim("role", "ROLE_" + ROLE)
                .withIssuer("MyPaintings")
                .withAudience("some-other-api")
                .withIssuedAt(new Date())
                .withExpiresAt(new Date(System.currentTimeMillis() + EXPIRATION_MS))
                .sign(Algorithm.HMAC256(SECRET));

        // when & then
        assertThatThrownBy(() -> jwtService.verifyToken(token))
                .isInstanceOf(JWTVerificationException.class)
                .hasMessageContaining("audience");
    }

    @Test
    @DisplayName("Should throw TokenExpiredException when verifying expired token")
    void verifyToken_shouldRejectExpiredToken() {
        // given
        String expired = JWT.create()
                .withClaim("userId", USER_ID)
                .withClaim("role", "ROLE_" + ROLE)
                .withIssuer("MyPaintings")
                .withAudience("mypaintings-api")
                .withIssuedAt(new Date(System.currentTimeMillis() - 120_000))
                .withExpiresAt(new Date(System.currentTimeMillis() - 60_000))
                .sign(Algorithm.HMAC256(SECRET));

        // when & then
        assertThatThrownBy(() -> jwtService.verifyToken(expired))
                .isInstanceOf(TokenExpiredException.class);
    }

    @Test
    @DisplayName("Should reject malformed token string")
    void verifyToken_shouldRejectMalformedToken() {
        // when & then
        assertThatThrownBy(() -> jwtService.verifyToken("not-a-jwt"))
                .isInstanceOf(JWTVerificationException.class);
    }

    @Test
    @DisplayName("Should reject tampered token due to signature mismatch")
    void verifyToken_shouldRejectTamperedToken() {
        // given
        String valid = jwtService.generateToken(USER_ID, ROLE);
        String[] parts = valid.split("\\.");
        String tampered = parts[0] + "." + parts[1] + "x" + "." + parts[2];

        // when & then
        assertThatThrownBy(() -> jwtService.verifyToken(tampered))
                .isInstanceOf(JWTVerificationException.class);
    }

    @Test
    @DisplayName("Validation should pass when secret is long enough")
    void validate_shouldPass_whenSecretIsLongEnough() {
        // when & then
        jwtService.validate();
    }

    @Test
    @DisplayName("Validation should throw IllegalStateException when secret is null")
    void validate_shouldThrow_whenSecretIsNull() {
        // given
        ReflectionTestUtils.setField(jwtService, "secretKey", null);

        // when & then
        assertThatThrownBy(jwtService::validate)
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("at least 32");
    }

    @Test
    @DisplayName("Validation should throw IllegalStateException when secret is shorter than 32 characters")
    void validate_shouldThrow_whenSecretTooShort() {
        // given
        ReflectionTestUtils.setField(jwtService, "secretKey", "short-secret");

        // when & then
        assertThatThrownBy(jwtService::validate)
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("at least 32");
    }

    @Test
    @DisplayName("Validation should pass when secret has exactly boundary length of 32 characters")
    void validate_shouldPass_whenSecretIsExactly32Chars() {
        // given
        ReflectionTestUtils.setField(jwtService, "secretKey", "a".repeat(32));

        // when & then
        jwtService.validate();
    }
}